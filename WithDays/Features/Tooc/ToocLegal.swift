import SwiftUI

/// 利用規約 and プライバシーポリシー, read in the app (from tooc について, or from the sign-up form).
enum ToocLegalDocument: String, Identifiable {
    case terms, privacy
    var id: String { rawValue }

    var title: String {
        switch self {
        case .terms: "利用規約"
        case .privacy: "プライバシーポリシー"
        }
    }

    static let enacted = "2026年11月26日 制定"

    var preface: String {
        switch self {
        case .terms:
            "この利用規約（以下「本規約」）は、トークアプリ tooc（WithDays の中で使う tooc を含みます。以下「本サービス」）の利用条件を定めるものです。本サービスを利用するすべての方（以下「利用者」）は、本規約に同意したうえで本サービスを利用するものとします。"
        case .privacy:
            "本サービスの提供者（以下「提供者」）は、tooc（WithDays の中で使う tooc を含みます。以下「本サービス」）における利用者の情報を、以下のとおり取り扱います。"
        }
    }

    var sections: [(heading: String, body: String)] {
        switch self {
        case .terms: [
            ("第1条（適用）",
             "本規約は、利用者と本サービスの提供者（以下「提供者」）との間の、本サービスの利用に関わる一切の関係に適用されます。アプリ内で別に示すルールや説明も、本規約の一部を構成します。"),
            ("第2条（アカウント）",
             "利用者は、toocID とパスワードを決めてアカウントを作成します。アカウントとパスワードは利用者自身の責任で管理し、第三者に使わせたり、譲り渡したりしてはなりません。アカウントが第三者に使われたことによる損害について、提供者は責任を負いません。"),
            ("第3条（禁止事項）",
             "利用者は、次の行為をしてはなりません。\n・法令または公序良俗に反する行為\n・他の利用者や第三者への嫌がらせ、脅迫、差別、なりすまし\n・他人の権利（著作権、肖像権、プライバシーなど）を侵害する内容の送信\n・わいせつな内容、暴力的な内容、スパムや勧誘を目的とする内容の送信\n・本サービスのサーバーやネットワークに過度な負荷をかける行為、不正アクセス、解析や改変\n・その他、提供者が不適切と判断する行為"),
            ("第4条（送信した内容）",
             "利用者が送信したメッセージ、写真、ファイル、ノート、アルバムなどの内容の権利は、利用者（または正当な権利者）に帰属します。提供者は、本サービスを提供するために必要な範囲でのみ、これらを保存・送信・表示します。送信した内容については、利用者が責任を負うものとします。"),
            ("第5条（利用の制限・アカウントの停止）",
             "利用者が本規約に違反した場合、提供者は事前の通知なく、送信した内容の削除、本サービスの利用の制限、またはアカウントの停止を行うことがあります。"),
            ("第6条（サービスの変更・中断・終了）",
             "提供者は、利用者に通知することなく、本サービスの内容を変更し、または提供を中断・終了することがあります。これによって利用者に生じた損害について、提供者は責任を負いません。"),
            ("第7条（免責）",
             "提供者は、本サービスに不具合がないこと、メッセージなどが確実に届き保存されること、特定の目的に適合することを保証しません。利用者どうしの間で生じたトラブルは、当事者間で解決するものとします。ただし、提供者の故意または重大な過失による場合はこの限りではありません。"),
            ("第8条（退会）",
             "利用者は、設定の「アカウント」からいつでもアカウントを削除できます。削除したアカウントは元に戻せません。"),
            ("第9条（規約の変更）",
             "提供者は、必要に応じて本規約を変更できます。変更後の本規約は、アプリ内に表示した時点から効力を持ち、その後に本サービスを利用した利用者は、変更に同意したものとみなします。"),
            ("第10条（準拠法・裁判管轄）",
             "本規約は日本法に従って解釈されます。本サービスに関して紛争が生じた場合は、提供者の所在地を管轄する裁判所を専属的合意管轄とします。"),
