             "取得した情報は、次の目的にのみ使います。\n・アカウントの作成と認証\n・メッセージなどを相手に届け、保存し、表示するため\n・友だちの追加や検索（toocID による検索は、設定の「プライバシー」でオフにできます）\n・不正な利用の防止と、問題が起きたときの対応\n・通報の受付と対応（通報した内容は、通報用のアカウント @tooc.report に届きます）\n・本サービスの改善"),
            ("3. 保存する場所",
             "情報は、Google LLC が提供する Firebase（Authentication、Cloud Firestore、Cloud Storage）に保存されます。そのため、情報が日本国外のサーバーに保存される場合があります。"),
            ("4. 第三者への提供",
             "提供者は、次の場合を除いて、利用者の情報を第三者に提供しません。\n・利用者が同意した場合（トークの相手に内容が届くことを含みます）\n・法令に基づく場合\n・人の生命、身体または財産を守るために必要で、本人の同意を得ることが難しい場合"),
            ("5. 端末の中だけにある情報",
             "パスコードロックのパスコード、Face ID の設定、下書き、ピン留めや非表示などの表示の設定は、利用者の端末の中だけに保存され、提供者に送られることはありません。Face ID の顔のデータは iPhone の中で扱われ、本サービスが取得することはありません。"),
            ("6. 情報の削除",
             "利用者は、送信したメッセージを取り消したり、アカウントを削除したりできます。アカウントを削除すると、プロフィールは削除されたアカウントとして表示されるようになり、ログインできなくなります。トークの相手の端末に届いた内容は、相手の側に残る場合があります。"),
            ("7. 安全管理",
             "提供者は、情報の漏えい、紛失、改ざんを防ぐため、通信の暗号化やアクセスの制限など、適切な対策をとります。"),
            ("8. ポリシーの変更",
             "提供者は、必要に応じて本ポリシーを変更することがあります。変更後の内容は、アプリ内に表示した時点から効力を持ちます。"),
        ]
        }
    }
}

struct ToocLegalView: View {
    let document: ToocLegalDocument

    var body: some View {
        ScrollView {
            VStack(alignment: .leading, spacing: 20) {
                Text(document.preface)
                    .toocFont(.subheadline)
                ForEach(Array(document.sections.enumerated()), id: \.offset) { _, section in
                    VStack(alignment: .leading, spacing: 6) {
                        Text(section.heading)
                            .toocFont(.headline)
                        Text(section.body)
                            .toocFont(.subheadline)
                            .foregroundStyle(.secondary)
                            .fixedSize(horizontal: false, vertical: true)
                    }
                }
                Text(ToocLegalDocument.enacted)
                    .toocFont(.footnote)
                    .foregroundStyle(.secondary)
                    .frame(maxWidth: .infinity, alignment: .trailing)
            }
            .padding(20)
            .textSelection(.enabled)
        }
        .navigationTitle(document.title)
        .navigationBarTitleDisplayMode(.inline)
    }
}
